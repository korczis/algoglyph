#!/usr/bin/env node
// Rewrites the derived regions of README.md from the code: the plate registry
// (src/plates/index.ts, loaded through Vite's SSR loader so the README sees exactly what the
// site ships) and the test suite (vitest's own collection). Everything between the markers
//   <!-- algoglyph:derived:begin <region> --> ... <!-- algoglyph:derived:end <region> -->
// is generated; everything outside them is authored and left untouched.
//
//   node scripts/build-readme.mjs           rewrite README.md
//   node scripts/build-readme.mjs --check   exit 1 when README.md is not what it would write
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const README = resolve(ROOT, 'README.md');
const PREVIEWS = 'docs/previews';
const SITE = 'https://korczis.github.io/algoglyph/';
const check = process.argv.includes('--check');

const NOTICE = '<!-- Generated by scripts/build-readme.mjs from src/plates/index.ts%s. '
  + 'Do not edit by hand: run `npm run readme`. -->';

async function loadRegistry() {
  const server = await createServer({
    root: ROOT,
    server: { middlewareMode: true },
    appType: 'custom',
    logLevel: 'silent',
  });
  try {
    const { PLATES, CATEGORIES } = await server.ssrLoadModule('/src/plates/index.ts');
    return { plates: PLATES, categories: CATEGORIES };
  } finally {
    await server.close();
  }
}

// --no-staticParse makes vitest import the test files to collect them, so `it.each` tables
// count as the cases they expand to (the static parser counts each table once).
function countTests() {
  const res = spawnSync('npx', ['--no', 'vitest', 'list', '--json', '--no-staticParse'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (res.status !== 0) {
    process.stderr.write(res.stderr ?? '');
    fail(`\`npx vitest list --json --no-staticParse\` exited ${res.status}`);
  }
  let tests;
  try {
    tests = JSON.parse(res.stdout);
  } catch {
    fail('`npx vitest list --json --no-staticParse` did not print JSON');
  }
  return { tests: tests.length, files: new Set(tests.map((t) => t.file)).size };
}

function fail(message) {
  console.error(`build-readme: ${message}`);
  process.exit(1);
}

const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const is3d = (plate) => plate.mode === 'webgl';
const dims = (plate) => (is3d(plate) ? '3D' : '2D');
const link = (plate) => `${SITE}#/p/${plate.id}`;
const html = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');
const md = (s) => String(s).replace(/([\\`*_[\]<>|])/g, '\\$1');

function preview(plate) {
  const dark = `${PREVIEWS}/${plate.id}.jpg`;
  if (!existsSync(resolve(ROOT, dark))) return null;
  const light = `${PREVIEWS}/${plate.id}-light.jpg`;
  return { dark, light: existsSync(resolve(ROOT, light)) ? light : null };
}

function byCategory(plates, categories) {
  return categories
    .map((c) => ({ ...c, plates: plates.filter((p) => p.category === c.id) }))
    .filter((c) => c.plates.length > 0);
}

function countsRegion({ plates, categories }, suite) {
  const groups = byCategory(plates, categories);
  const webgl = plates.filter(is3d).length;
  const pointer = plates.filter((p) => p.interaction).length;
  const perCategory = groups.map((c) => `${c.label} ${c.plates.length}`).join(' · ');
  return [
    NOTICE.replace('%s', ' and `vitest list`'),
    `<p align="center"><b>${plural(plates.length, 'plate')}</b>: ${perCategory}.<br>`
      + `${webgl} drawn in 3D (p5 WEBGL), ${plates.length - webgl} in 2D; `
      + `${pointer} ${pointer === 1 ? 'responds' : 'respond'} to the pointer.<br>`
      + `<b>${plural(suite.tests, 'unit test')}</b> in ${plural(suite.files, 'file')}.</p>`,
  ].join('\n');
}

function metaParts(plate) {
  return [dims(plate), plate.complexity, plate.tags.join(', ')];
}

function listItem(plate) {
  const meta = metaParts(plate).map(md).join(' · ');
  const lines = [
    `- **[${plate.no} · ${md(plate.title)}](${link(plate)})**  `,
    `  ${md(plate.summary)}  `,
    `  <sub>${meta}</sub>`,
  ];
  if (plate.interaction) lines[2] += '  ';
  if (plate.interaction) lines.push(`  <sub>Pointer: ${md(plate.interaction)}</sub>`);
  return lines.join('\n');
}

function gridCell(plate) {
  const img = preview(plate);
  const out = ['<td width="50%" valign="top">'];
  if (img) {
    const alt = html(`${plate.title}, plate ${plate.no}`);
    const source = img.light
      ? `<source media="(prefers-color-scheme: light)" srcset="${img.light}">`
      : '';
    out.push(`<a href="${link(plate)}"><picture>${source}`
      + `<img src="${img.dark}" width="100%" alt="${alt}"></picture></a><br>`);
  }
  out.push(`<b><a href="${link(plate)}">${plate.no} · ${html(plate.title)}</a></b><br>`);
  out.push(`${html(plate.summary)}<br>`);
  out.push(`<sub>${metaParts(plate).map(html).join(' · ')}</sub>`);
  if (plate.interaction) out.push(`<br><sub>Pointer: ${html(plate.interaction)}</sub>`);
  out.push('</td>');
  return out.join('\n');
}

function grid(plates) {
  const rows = [];
  for (let i = 0; i < plates.length; i += 2) {
    const cells = plates.slice(i, i + 2).map(gridCell);
    if (cells.length === 1) cells.push('<td width="50%"></td>');
    rows.push(['<tr>', ...cells, '</tr>'].join('\n'));
  }
  return ['<table>', ...rows, '</table>'].join('\n');
}

function catalogueRegion({ plates, categories }) {
  // One layout for the whole catalogue: the grid once any preview exists, a list until then.
  const withGrid = plates.some((p) => preview(p));
  const out = [NOTICE.replace('%s', '')];
  for (const c of byCategory(plates, categories)) {
    const span = `${c.plates[0].no}–${c.plates[c.plates.length - 1].no}`;
    out.push('', `### ${c.label}`, '', `<sub>${plural(c.plates.length, 'plate')}, ${span}</sub>`);
    out.push('', withGrid ? grid(c.plates) : c.plates.map(listItem).join('\n'));
  }
  return out.join('\n');
}

function splice(text, region, body) {
  const begin = `<!-- algoglyph:derived:begin ${region} -->`;
  const end = `<!-- algoglyph:derived:end ${region} -->`;
  const i = text.indexOf(begin);
  const j = text.indexOf(end);
  if (i < 0 || j < 0 || j < i || text.indexOf(begin, i + 1) >= 0) {
    fail(`README.md needs exactly one "${begin}" followed by "${end}"`);
  }
  return `${text.slice(0, i + begin.length)}\n${body}\n${text.slice(j)}`;
}

const registry = await loadRegistry();
const suite = countTests();
const current = readFileSync(README, 'utf8');
let next = splice(current, 'counts', countsRegion(registry, suite));
next = splice(next, 'catalogue', catalogueRegion(registry));

const where = relative(process.cwd(), README) || 'README.md';
if (check) {
  if (next !== current) {
    fail(`${where} derived sections are stale (plate registry, tests or previews changed). `
      + 'Run `npm run readme` and commit the result.');
  }
  console.log(`build-readme: ${where} derived sections are current`);
} else if (next !== current) {
  writeFileSync(README, next);
  console.log(`build-readme: ${where} rewritten`);
} else {
  console.log(`build-readme: ${where} already current`);
}
