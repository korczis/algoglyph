#!/usr/bin/env node
// Rewrites the derived regions of README.md from the catalogue (scripts/lib/catalogue.mjs, the
// same model the site is built from) and the test suite (vitest's own collection). Everything between the markers
//   <!-- algoglyph:derived:begin <region> --> ... <!-- algoglyph:derived:end <region> -->
// is generated; everything outside them is authored and left untouched.
//
//   node scripts/build-readme.mjs           rewrite README.md
//   node scripts/build-readme.mjs --check   exit 1 when README.md is not what it would write
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadCatalogue } from './lib/catalogue.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const README = resolve(ROOT, 'README.md');
const PREVIEWS = 'docs/previews';
const SITE = 'https://korczis.github.io/algoglyph/';
const check = process.argv.includes('--check');

const NOTICE = '<!-- Generated by scripts/build-readme.mjs from catalogue/%s. '
  + 'Do not edit by hand: run `npm run readme`. -->';

function loadModel() {
  const { errors, model } = loadCatalogue(ROOT);
  if (errors.length) fail(`the catalogue has ${errors.length} error(s); run npm run catalogue`);
  return model;
}

// --no-staticParse makes vitest import the test files to collect them, so `it.each` tables
// count as the cases they expand to (the static parser counts each table once).
function countTests() {
  const res = spawnSync('npx', ['--no', 'vitest', 'list', '--json', '--no-staticParse'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  if (res.status !== 0) {
    process.stderr.write(res.stderr ?? '');
    fail(`\`npx vitest list --json --no-staticParse\` exited ${res.status}`);
  }
  let tests;
  try {
    tests = JSON.parse(res.stdout);
  } catch {
    fail('`npx vitest list --json --no-staticParse` did not print JSON');
  }
  return { tests: tests.length, files: new Set(tests.map((t) => t.file)).size };
}

function fail(message) {
  console.error(`build-readme: ${message}`);
  process.exit(1);
}

const plural = (n, one, many = `${one}s`) => `${n} ${n === 1 ? one : many}`;
const link = (e) => `${SITE}#/p/${e.id}`;
const html = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
  .replace(/"/g, '&quot;');

function preview(e) {
  const dark = `${PREVIEWS}/${e.id}.jpg`;
  if (!existsSync(resolve(ROOT, dark))) return null;
  const light = `${PREVIEWS}/${e.id}-light.jpg`;
  return { dark, light: existsSync(resolve(ROOT, light)) ? light : null };
}

const nodeOf = (model, key) => model.nodes.find((n) => n.key === key);

function countsRegion(model, suite) {
  const live = model.entries.filter((e) => e.status === 'live').length;
  const planned = model.entries.length - live;
  const wings = model.roots.map((k) => nodeOf(model, k))
    .map((w) => `${w.title} ${w.live}/${w.live + w.planned}`).join(' · ');
  return [
    NOTICE.replace('%s', ' and `vitest list`'),
    `<p align="center"><b>${plural(live, 'live plate')}</b> and ${planned} planned, `
      + `${plural(model.labs.length, 'comparison lab')}, in ${plural(model.roots.length, 'wing')}:<br>`
      + `<sub>${html(wings)}</sub><br>`
      + `<b>${plural(suite.tests, 'unit test')}</b> in ${plural(suite.files, 'file')}.</p>`,
  ].join('\n');
}

function metaParts(model, e) {
  return [nodeOf(model, e.taxonomy)?.title ?? e.taxonomy, e.complexity, e.tags.join(', ')].filter(Boolean);
}

function gridCell(model, e) {
  const img = preview(e);
  const out = ['<td width="50%" valign="top">'];
  if (img) {
    const alt = html(`${e.title}, plate ${e.no}`);
    const source = img.light ? `<source media="(prefers-color-scheme: light)" srcset="${img.light}">` : '';
    out.push(`<a href="${link(e)}"><picture>${source}<img src="${img.dark}" width="100%" alt="${alt}"></picture></a><br>`);
  }
  out.push(`<b><a href="${link(e)}">${e.no} · ${html(e.title)}</a></b><br>`);
  out.push(`${html(e.summary)}<br>`);
  out.push(`<sub>${metaParts(model, e).map(html).join(' · ')}</sub>`);
  if (e.interaction) out.push(`<br><sub>Pointer: ${html(e.interaction)}</sub>`);
  out.push('</td>');
  return out.join('\n');
}

function grid(model, entries) {
  const rows = [];
  for (let i = 0; i < entries.length; i += 2) {
    const cells = entries.slice(i, i + 2).map((e) => gridCell(model, e));
    if (cells.length === 1) cells.push('<td width="50%"></td>');
    rows.push(['<tr>', ...cells, '</tr>'].join('\n'));
  }
  return ['<table>', ...rows, '</table>'].join('\n');
}

function catalogueRegion(model) {
  const out = [NOTICE.replace('%s', '')];
  for (const key of model.roots) {
    const w = nodeOf(model, key);
    const all = model.entries.filter((e) => e.path[0] === key);
    const live = all.filter((e) => e.status === 'live');
    const planned = all.filter((e) => e.status === 'planned');
    out.push('', `### ${w.title}`, '', `<sub>${html(w.summary)} ${plural(live.length, 'live plate')}, ${planned.length} planned.</sub>`);
    if (live.length) out.push('', grid(model, live));
    if (planned.length) {
      out.push('', `<details><summary>${plural(planned.length, 'planned algorithm')}</summary>`, '');
      out.push(planned.map((e) => `- [${e.no} · ${e.title.replace(/([\\`*_[\]<>|])/g, '\\$1')}](${link(e)})`).join('\n'));
      out.push('', '</details>');
    }
  }
  return out.join('\n');
}

function splice(text, region, body) {
  const begin = `<!-- algoglyph:derived:begin ${region} -->`;
  const end = `<!-- algoglyph:derived:end ${region} -->`;
  const i = text.indexOf(begin);
  const j = text.indexOf(end);
  if (i < 0 || j < 0 || j < i || text.indexOf(begin, i + 1) >= 0) {
    fail(`README.md needs exactly one "${begin}" followed by "${end}"`);
  }
  return `${text.slice(0, i + begin.length)}\n${body}\n${text.slice(j)}`;
}

const model = loadModel();
const suite = countTests();
const current = readFileSync(README, 'utf8');
let next = splice(current, 'counts', countsRegion(model, suite));
next = splice(next, 'catalogue', catalogueRegion(model));

const where = relative(process.cwd(), README) || 'README.md';
if (check) {
  if (next !== current) {
    fail(`${where} derived sections are stale (catalogue, tests or previews changed). `
      + 'Run `npm run readme` and commit the result.');
  }
  console.log(`build-readme: ${where} derived sections are current`);
} else if (next !== current) {
  writeFileSync(README, next);
  console.log(`build-readme: ${where} rewritten`);
} else {
  console.log(`build-readme: ${where} already current`);
}
