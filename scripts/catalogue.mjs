#!/usr/bin/env node
// The catalogue's tooling (ADR 0004). One parser (scripts/lib/catalogue.mjs) behind every verb.
//
//   npm run catalogue                      validate; print what the collection holds
//   npm run catalogue -- --check           validate and refuse stale derived files (the plan)
//   npm run catalogue -- stats [--json]    counts by wing, shelf, engine and status
//   npm run catalogue -- list [--status live|planned] [--engine <e>] [--under <path>]
//   npm run catalogue -- new <id> --title "<t>" --taxonomy <wing/shelf> --engine <e>
//                                          [--kernel]   scaffold an entry (and a kernel)
//   npm run catalogue -- plan [--write]    the .ai/repo/project milestones and issues derived
//                                          from the planned entries (dry run without --write)
//
// Exit 0 ok, 1 a validation error or stale derived file, 2 a usage error.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse as parseYaml, stringify } from 'yaml';
import { ENGINES, loadCatalogue } from './lib/catalogue.mjs';
import { derivePlan } from './lib/plan.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flag = (name) => args.includes(name);
const opt = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const verb = args[0] && !args[0].startsWith('--') ? args[0] : 'validate';
const die = (code, msg) => { console.error(`catalogue: ${msg}`); process.exit(code); };

function load() {
  const r = loadCatalogue(ROOT);
  if (r.errors.length) {
    for (const e of r.errors) console.error(`  ${e}`);
    die(1, `${r.errors.length} error(s)`);
  }
  return r.model;
}

// ---- the derived plan ---------------------------------------------------------------------
const PROJECT = join(ROOT, '.ai/repo/project');
const GENERATED = '# Generated by scripts/catalogue.mjs plan from catalogue/: the keys below are derived;\n'
  + '# the plan state Majordomus records (started_at, evidence, ...) is kept across regeneration.\n';
// keys this generator owns; every other key in an existing file is plan state and is kept
const OWN_M = ['id', 'title', 'slug', 'order', 'priority', 'problem', 'outcome', 'acceptance_criteria',
  'validation', 'evidence_required', 'scope'];
const OWN_I = ['id', 'milestone', 'title', 'slug', 'priority', 'profile', 'objective', 'why', 'scope',
  'depends_on', 'acceptance_criteria', 'validation', 'evidence_required', 'parallel_safe'];
const header = (text) => (text.startsWith('# Generated by scripts/catalogue.mjs') ? text : `${GENERATED}${text}`);
const pick = (o, keys) => Object.fromEntries(keys.filter((k) => o[k] !== undefined).map((k) => [k, o[k]]));

function planFiles(model) {
  const { milestones, issues } = derivePlan(model);
  const out = [];
  for (const [list, dir, own] of [[milestones, 'milestones', OWN_M], [issues, 'issues', OWN_I]]) {
    for (const obj of list) {
      const file = join(PROJECT, dir, `${obj.id}.yaml`);
      const old = existsSync(file) ? parseYaml(readFileSync(file, 'utf8')) ?? {} : {};
      const state = Object.fromEntries(Object.entries(old).filter(([k]) => !own.includes(k)));
      if (!state.created_at) state.created_at = new Date().toISOString().slice(0, 10);
      const next = { ...obj, ...state };
      const same = existsSync(file) && JSON.stringify(pick(old, own)) === JSON.stringify(pick(obj, own));
      out.push({ file, same, text: header(stringify(next, { lineWidth: 0 })) });
    }
    // a generated file the catalogue no longer implies is removed, unless Majordomus recorded
    // plan state in it (it was started or verified): that is history and is kept
    const wanted = new Set(list.map((o) => `${o.id}.yaml`));
    const prefix = dir === 'milestones' ? 'MC-' : 'IC-';
    const dirPath = join(PROJECT, dir);
    for (const f of existsSync(dirPath) ? readdirSync(dirPath) : []) {
      if (!f.startsWith(prefix) || wanted.has(f)) continue;
      const old = parseYaml(readFileSync(join(dirPath, f), 'utf8')) ?? {};
      const state = Object.keys(old).filter((k) => !own.includes(k) && k !== 'created_at');
      if (!state.length) out.push({ file: join(dirPath, f), same: false, remove: true });
    }
  }
  return out;
}

// ---- verbs --------------------------------------------------------------------------------
if (verb === 'validate') {
  const model = load();
  const live = model.entries.filter((e) => e.status === 'live').length;
  let stale = 0;
  if (flag('--check')) {
    for (const f of planFiles(model)) if (!f.same) { console.error(`  stale: ${f.file.slice(ROOT.length + 1)}`); stale++; }
  }
  console.log(`catalogue: ${model.entries.length} entries (${live} live, ${model.entries.length - live} planned), `
    + `${model.roots.length} wings, ${model.nodes.length - model.roots.length} shelves, ${model.labs.length} lab(s)`);
  if (stale) die(1, `${stale} derived plan file(s) are stale; run npm run catalogue -- plan --write`);
} else if (verb === 'stats') {
  const model = load();
  const count = (xs) => ({ live: xs.filter((e) => e.status === 'live').length, planned: xs.filter((e) => e.status === 'planned').length });
  const stats = {
    total: count(model.entries),
    wings: Object.fromEntries(model.roots.map((k) => [k, count(model.entries.filter((e) => e.path[0] === k))])),
    engines: Object.fromEntries(ENGINES.map((g) => [g, count(model.entries.filter((e) => e.engine === g))]).filter(([, c]) => c.live + c.planned)),
  };
  if (flag('--json')) console.log(JSON.stringify(stats, null, 2));
  else {
    const row = (k, c) => `  ${k.padEnd(14)} ${String(c.live).padStart(4)} live ${String(c.planned).padStart(4)} planned`;
    console.log(`total\n${row('', stats.total)}\nwings`);
    for (const [k, c] of Object.entries(stats.wings)) console.log(row(k, c));
    console.log('engines');
    for (const [k, c] of Object.entries(stats.engines)) console.log(row(k, c));
  }
} else if (verb === 'list') {
  const model = load();
  const status = opt('--status');
  const engine = opt('--engine');
  const under = opt('--under');
  for (const e of model.entries) {
    if (status && e.status !== status) continue;
    if (engine && e.engine !== engine) continue;
    if (under && !(e.taxonomy === under || e.taxonomy.startsWith(`${under}/`))) continue;
    console.log(`${e.no}  ${e.status.padEnd(7)}  ${e.engine.padEnd(10)}  ${e.taxonomy.padEnd(30)}  ${e.id}`);
  }
} else if (verb === 'new') {
  const id = args[1];
  const title = opt('--title');
  const taxonomy = opt('--taxonomy');
  const engine = opt('--engine');
  if (!id || !title || !taxonomy || !engine) die(2, 'usage: new <id> --title "<t>" --taxonomy <wing/shelf> --engine <e> [--kernel]');
  if (!ENGINES.includes(engine)) die(2, `engine must be one of ${ENGINES.join(', ')}`);
  const file = join(ROOT, 'catalogue/entries', `${id}.md`);
  if (existsSync(file)) die(2, `${id} exists`);
  const kernel = flag('--kernel');
  const fm = { id, title, taxonomy, status: kernel ? 'live' : 'planned', engine, tags: [engine] };
  writeFileSync(file, `---\n${stringify(fm, { lineWidth: 0 })}---\n\nOne sentence: what the plate shows and how to read it.\n${kernel ? '\nReading notes: what to try, what the readouts count.\n' : ''}`);
  console.log(`catalogue: wrote catalogue/entries/${id}.md`);
  if (kernel) {
    const dir = engine === 'custom' ? join(ROOT, 'src/plates', id) : join(ROOT, 'src/kernels', engine);
    mkdirSync(dir, { recursive: true });
    const k = engine === 'custom' ? join(dir, 'plate.ts') : join(dir, `${id}.ts`);
    if (!existsSync(k)) {
      writeFileSync(k, engine === 'array'
        ? `import type { ArrayKernel, ArrayOps } from '../../engines/array/trace';\n\n// ${title}\nexport const kernel: ArrayKernel = {\n  run(a: ArrayOps) {\n    void a;\n  },\n};\n`
        : `// ${title}: implement the ${engine} contract here (src/engines/${engine}).\nexport const kernel = {};\n`);
      console.log(`catalogue: wrote ${k.slice(ROOT.length + 1)}`);
    }
  }
} else if (verb === 'plan') {
  const model = load();
  const files = planFiles(model);
  for (const f of files) {
    if (f.same) continue;
    const rel = f.file.slice(ROOT.length + 1);
    if (flag('--write')) {
      if (f.remove) {
        rmSync(f.file);
        console.log(`catalogue: removed ${rel} (no planned entry implies it)`);
        continue;
      }
      mkdirSync(dirname(f.file), { recursive: true });
      writeFileSync(f.file, f.text);
      console.log(`catalogue: wrote ${rel}`);
    } else console.log(`catalogue: would ${f.remove ? 'remove' : 'write'} ${rel}`);
  }
  console.log(`catalogue: plan of ${files.length} file(s), ${files.filter((f) => !f.same).length} changed`);
} else die(2, `unknown verb ${verb}`);
