//! The crate's build script: generates the sorting plugin registry.
//!
//! Every `src/sorting/algorithms/<stem>.rs` is a plugin. The generated `sorting_registry.rs`
//! declares one module per file (by absolute `#[path]`) and one `Entry` per module, sorted by
//! stem, so adding an algorithm never edits a shared file. It also carries `FINGERPRINT`, an
//! FNV-1a hash of every source the traces depend on, which keys the browser's trace cache
//! together with the crate version.
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn is_ident(stem: &str) -> bool {
    let mut chars = stem.chars();
    match chars.next() {
        Some(c) if c.is_ascii_lowercase() || c == '_' => {}
        _ => return false,
    }
    chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_')
}

fn fnv(mut h: u64, bytes: &[u8]) -> u64 {
    for &b in bytes {
        h ^= b as u64;
        h = h.wrapping_mul(0x0000_0100_0000_01B3);
    }
    h
}

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let sorting = manifest.join("src").join("sorting");
    let dir = sorting.join("algorithms");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed={}", file!());

    let mut plugins: Vec<(String, PathBuf)> = Vec::new();
    if let Ok(entries) = fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("rs") {
                continue;
            }
            let stem = match path.file_stem().and_then(|s| s.to_str()) {
                Some(s) => s.to_string(),
                None => continue,
            };
            if stem == "mod" {
                continue;
            }
            if !is_ident(&stem) {
                panic!(
                    "plugin file name is not a valid module name: {}",
                    path.display()
                );
            }
            println!("cargo:rerun-if-changed={}", path.display());
            plugins.push((stem, path));
        }
    }
    plugins.sort();

    let mut h: u64 = 0xCBF2_9CE4_8422_2325;
    h = fnv(
        h,
        env::var("CARGO_PKG_VERSION").unwrap_or_default().as_bytes(),
    );
    for shared in ["prelude.rs", "kit.rs", "mod.rs"] {
        let p = sorting.join(shared);
        println!("cargo:rerun-if-changed={}", p.display());
        h = fnv(h, &fs::read(&p).unwrap_or_default());
    }
    for (stem, path) in &plugins {
        h = fnv(h, stem.as_bytes());
        h = fnv(h, &fs::read(path).unwrap_or_default());
    }

    let mut s = String::new();
    s.push_str(
        "// @generated by src/sorting/build.rs from src/sorting/algorithms/*.rs; do not edit.\n",
    );
    s.push_str("pub mod algorithms {\n");
    for (stem, path) in &plugins {
        s.push_str(&format!(
            "    #[path = {:?}]\n    pub mod {};\n",
            path.display().to_string(),
            stem
        ));
    }
    s.push_str("}\n\n");
    s.push_str("/// Every plugin, sorted by file stem.\n");
    s.push_str("pub static REGISTRY: &[crate::sorting::prelude::Entry] = &[\n");
    for (stem, _) in &plugins {
        s.push_str(&format!(
            concat!(
                "    crate::sorting::prelude::Entry {{ stem: {0:?}, ",
                "meta: &algorithms::{0}::META, sort: algorithms::{0}::sort }},\n"
            ),
            stem
        ));
    }
    s.push_str("];\n\n");
    s.push_str("/// FNV-1a of the crate version and every source a trace depends on.\n");
    s.push_str(&format!("pub const FINGERPRINT: u64 = 0x{h:016x};\n"));

    let out = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    let target = Path::new(&out).join("sorting_registry.rs");
    if fs::read_to_string(&target).ok().as_deref() != Some(s.as_str()) {
        fs::write(&target, s).expect("write sorting_registry.rs");
    }
}
